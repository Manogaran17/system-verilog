class packet;
  
  rand bit [7:0]addr;
  rand bit [7:0]data;
  constraint addr_c{
    addr dist{
      0 :=50,
      [0:10]:=20,
      [11:50]:=10,
      [51:100]:=5,
      255:=100
      
    };
  }
    
    constraint data_c{
    data dist{
      
      0 :=50,
      [0:10]:=20,
      [11:50]:=10,
      [51:100]:=5,
      255:=100
      
    };
  }
  
    function void display();
      $display("______________________________________");
      $display("ADDR = %d ",addr);
      $display("DATA = %d ",data);
      $display("______________________________________");
      
    endfunction
endclass

